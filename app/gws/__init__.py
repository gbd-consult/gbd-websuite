class User(Object):
    """User.

    A user has a set of roles, which are checked against the permissions of
    objects to decide access.
    """

    isGuest: bool
    """The user is the guest user."""

    authProvider: 'AuthProvider'
    """The provider that created the user."""

    attributes: dict
    """Public user attributes, sent to the client."""
    data: dict
    """Private user data from the provider."""
    roles: set[str]
    """User roles."""
    uid: str
    """Global user uid, made of the provider uid and the local uid."""

    authToken: str
    """Token for the ``token`` authentication method."""
    displayName: str
    """User display name."""
    email: str
    """User email."""
    localUid: str
    """User uid within its provider."""
    loginName: str
    """User login name."""
    mfaUid: str
    """Uid of the multi-factor adapter for this user, empty if none."""
    mfaSecret: str
    """Secret for the multi-factor adapter."""

    def acl_bit(self, access: Access, obj: Object) -> Optional[int]:
        """Get the access decision for an object itself, without parents.

        Args:
            access: Access mode.
            obj: The object.

        Returns:
            ``gws.c.ALLOW`` or ``gws.c.DENY`` if the object's permissions decide
            for one of the user's roles, ``None`` otherwise.
        """

    def can(self, access: Access, obj: Object, *context) -> bool:
        """Check if the user can access an object.

        If the object's permissions do not decide, the context objects are
        checked in turn, then the parents of the last checked object.

        Args:
            access: Access mode.
            obj: The object.
            *context: Further objects to check, before the parents.

        Returns:
            ``True`` if access is granted.
        """

    def can_create(self, obj: Object, *context) -> bool:
        """Check if the user has the ``create`` permission on an object.

        Args:
            obj: The object.
            *context: Further objects to check, before the parents.

        Returns:
            ``True`` if access is granted.
        """

    def can_delete(self, obj: Object, *context) -> bool:
        """Check if the user has the ``delete`` permission on an object.

        Args:
            obj: The object.
            *context: Further objects to check, before the parents.

        Returns:
            ``True`` if access is granted.
        """

    def can_read(self, obj: Object, *context) -> bool:
        """Check if the user has the ``read`` permission on an object.

        Args:
            obj: The object.
            *context: Further objects to check, before the parents.

        Returns:
            ``True`` if access is granted.
        """

    def can_use(self, obj: Object, *context) -> bool:
        """Check if the user can use an object, which requires the ``read`` permission.

        Args:
            obj: The object.
            *context: Further objects to check, before the parents.

        Returns:
            ``True`` if access is granted.
        """

    def can_write(self, obj: Object, *context) -> bool:
        """Check if the user has the ``write`` permission on an object.

        Args:
            obj: The object.
            *context: Further objects to check, before the parents.

        Returns:
            ``True`` if access is granted.
        """

    def can_edit(self, obj: Object, *context) -> bool:
        """Check if the user has any of the ``write``, ``create`` or ``delete`` permissions on an object.

        Args:
            obj: The object.
            *context: Further objects to check, before the parents.

        Returns:
            ``True`` if access is granted.
        """

    def has_role(self, role: str) -> bool:
        """Check if the user has a role.

        Args:
            role: Role name.

        Returns:
            ``True`` if the user has the role.
        """

    def acquire(self, uid: str = None, classref: Optional[ClassRef] = None, access: Optional[Access] = None) -> Optional[Object]:
        """Get an object by uid, if the user can access it.

        Args:
            uid: Object uid.
            classref: Class reference. If provided, the object must match it.
            access: Access mode, ``Access.read`` if omitted.

        Returns:
            The object, or ``None`` if it does not exist or the user may not access it.
        """

    def require(self, uid: str = None, classref: Optional[ClassRef] = None, access: Optional[Access] = None) -> Object:
        """Get an object by uid and fail if it is not found or not accessible.

        Args:
            uid: Object uid.
            classref: Class reference. If provided, the object must match it.
            access: Access mode, ``Access.read`` if omitted.

        Returns:
            The object.

        Raises:
            NotFoundError: If the object does not exist.
            ForbiddenError: If the user may not access the object.
        """

    def require_project(self, uid: str = None) -> 'Project':
        """Get a project the user can read.

        Args:
            uid: Project uid.

        Returns:
            The project.

        Raises:
            NotFoundError: If the project does not exist.
            ForbiddenError: If the user may not read the project.
        """

    def require_layer(self, uid=None) -> 'Layer':
        """Get a layer the user can read.

        Args:
            uid: Layer uid.

        Returns:
            The layer.

        Raises:
            NotFoundError: If the layer does not exist.
            ForbiddenError: If the user may not read the layer.
        """


