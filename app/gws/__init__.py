"""GBD WebSuite: basic types and interfaces.

The ``gws`` package holds the types that all parts of GBD WebSuite share: the
basic data containers, enums and type aliases, the error classes, the object
tree interfaces, the base ``Config`` and ``Props`` classes, and the interfaces
of all configurable objects (``gws.Layer``, ``gws.Map``, ``gws.Model``,
``gws.Grabber``, ``gws.Project``, ``gws.Application`` and many more). Every GWS
module imports it with ``import gws``.

``gws/__init__.py`` is generated by ``app/_make_init.py`` from this file
(``__init__.pyinc``). Each ``# @include`` line is replaced with the contents of
a ``*.pyinc`` fragment, so the types defined in ``core/*.pyinc`` and in the
``types.pyinc`` files of the other packages all end up in the ``gws``
namespace. The package also re-exports these modules of ``gws.core`` under
short names:

- ``gws.u``: general utilities (``gws.core.util``),
- ``gws.c``: constants (``gws.core.const``),
- ``gws.log``: logging,
- ``gws.debug``: debugging helpers,
- ``gws.env``: environment variables,

and ``gws.ext``, the decorators that register extension classes and command
methods.

Code base layout
----------------

- ``gws.core``: the lowest layer: basic types, the object tree, logging,
  constants and general utilities.
- ``gws.lib``: general purpose libraries (CRS, images, XML, networking, SVG,
  styles and so on), independent of the GWS object tree.
- ``gws.gis``: GIS functionality built on ``lib``: map rendering, zoom
  levels, source layers and tile caches.
- ``gws.base``: the base classes and managers of the configurable objects
  (application, projects, maps, layers, models, actions, auth and others).
- ``gws.plugin``: concrete implementations of the base classes (layer types,
  auth providers, OWS services, templates, model fields and so on), each
  registered with a ``gws.ext`` decorator.
- ``gws.config``: configuration parsing and loading, which builds the object
  tree from the configuration.
- ``gws.spec``: the spec generator and runtime: type metadata used to read
  configuration and requests and to find extension classes and commands.
- ``gws.server``: configuration and control of the embedded servers (uWSGI,
  NGINX, the spool server and the monitor).
- ``gws.ext``: the extension decorators (``gws.ext.object.*``,
  ``gws.ext.config.*``, ``gws.ext.props.*``, ``gws.ext.command.*``).
  ``gws/ext/__init__.py`` is generated as well.
- ``gws.test``: the test framework.

The intended import hierarchy is ``core < lib < gis < base < plugin``: each
layer imports only from the layers below it. ``config``, ``spec`` and
``server`` import ``lib`` and each other, and ``base`` imports them. Nothing
outside ``gws.plugin`` imports plugins; plugin classes are found through the
specs and loaded on demand.

Example::

    import gws
    import gws.base.layer

    d = gws.Data(name='roads', crs='EPSG:3857')
    d.name                                 # 'roads'
    d.title                                # None, missing attributes are None
    gws.u.get({'a': {'b': 1}}, 'a.b')      # 1

    @gws.ext.config.layer('my')
    class Config(gws.base.layer.Config):
        pass

    @gws.ext.object.layer('my')
    class Object(gws.base.layer.Object):
        def configure(self):
            gws.log.info(f'configuring {self.uid}')
"""

