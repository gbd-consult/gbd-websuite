class Image:
    """Raster image.

    Manipulation methods change the image in place and return the image itself, so that calls can be chained.
    """

    def size(self) -> Size:
        """Get the image size.

        Returns:
            A tuple ``(width, height)`` in pixels.
        """

    def mode(self) -> str:
        """Get the image mode.

        Returns:
            PIL image mode, e.g. ``RGBA``.
        """

    def convert(self, mode: str) -> 'Image':
        """Convert the image to a mode.

        Args:
            mode: PIL image mode.

        Returns:
            The image.
        """

    def add_box(self, color=None) -> 'Image':
        """Draw a 1 pixel wide frame along the image edges.

        The image is converted to RGBA.

        Args:
            color: Line color, black by default.

        Returns:
            The image.
        """

    def add_text(self, text: str, x=0, y=0, color=None) -> 'Image':
        """Draw text on the image with the default font.

        The image is converted to RGBA.

        Args:
            text: Text, can contain multiple lines.
            x: X coordinate of the top left corner of the text.
            y: Y coordinate of the top left corner of the text.
            color: Text color, black by default.

        Returns:
            The image.
        """

    def compose(self, other: 'Image', opacity=1) -> 'Image':
        """Place another image on top of this one, using alpha composition.

        The other image is resized to the size of this one if needed.

        Args:
            other: Image to place on top.
            opacity: Opacity of the other image, from 0 to 1.

        Returns:
            The image.
        """

    def crop(self, box) -> 'Image':
        """Crop the image.

        Args:
            box: Crop rectangle ``(left, upper, right, lower)`` in pixels.

        Returns:
            The image.
        """

    def paste(self, other: 'Image', where=None) -> 'Image':
        """Paste another image into this one.

        Args:
            other: Image to paste.
            where: Position ``(x, y)`` of the upper left corner, or a box ``(left, upper, right, lower)``.
                By default, the image is pasted at ``(0, 0)``.

        Returns:
            The image.
        """

    def resize(self, size: Size, **kwargs) -> 'Image':
        """Resize the image to a size, without keeping the aspect ratio.

        Args:
            size: New size ``(width, height)``.
            **kwargs: Options for ``PIL.Image.resize``. The default resampling is bicubic.

        Returns:
            The image.
        """

    def resize_to(self, width: int = 0, height: int = 0, **kwargs) -> 'Image':
        """Resize the image to a width, a height or both.

        If only one dimension is given, the other is computed to keep the aspect ratio.
        If none is given, the image is not changed.

        Args:
            width: New width.
            height: New height.
            **kwargs: Options for ``PIL.Image.resize``.

        Returns:
            The image.
        """

    def rotate(self, angle: int, **kwargs) -> 'Image':
        """Rotate the image counter-clockwise.

        Args:
            angle: Angle in degrees.
            **kwargs: Options for ``PIL.Image.rotate``. The default resampling is bicubic.

        Returns:
            The image.
        """

    def to_bytes(self, mime_type: Optional[str] = None, options: Optional[dict] = None) -> bytes:
        """Encode the image.

        The ``options`` dict can contain any PIL save option
        (see https://pillow.readthedocs.io/en/stable/handbook/image-file-formats.html).

        An additional option ``mode`` is the image mode
        (see https://pillow.readthedocs.io/en/stable/handbook/concepts.html#concept-modes).
        If provided, the image is converted to that mode before saving, with an adaptive palette.

        An additional option ``background`` sets the color to replace the alpha channel with
        when an RGBA image is saved as JPEG (default is white).

        Args:
            mime_type: MIME type of the output, PNG by default.
            options: Encoding options.

        Returns:
            The encoded image.
        """

    def to_base64(self, mime_type: Optional[str] = None, options: Optional[dict] = None) -> str:
        """Encode the image as a base64 string.

        Args:
            mime_type: MIME type of the output, PNG by default.
            options: Encoding options, as in ``to_bytes``.

        Returns:
            The base64 encoded image.
        """

    def to_data_url(self, mime_type: Optional[str] = None, options: Optional[dict] = None) -> str:
        """Encode the image as a base64 data URL.

        Args:
            mime_type: MIME type of the output, PNG by default.
            options: Encoding options, as in ``to_bytes``.

        Returns:
            A ``data:`` URL.
        """

    def to_path(self, path: str, mime_type: Optional[str] = None, options: Optional[dict] = None) -> str:
        """Encode the image and save it to a file.

        Args:
            path: File path.
            mime_type: MIME type of the output, PNG by default.
            options: Encoding options, as in ``to_bytes``.

        Returns:
            The file path.
        """

    def to_array(self) -> 'numpy.typing.NDArray':
        """Convert the image to a numpy array.

        Returns:
            An array of shape ``(height, width)`` or ``(height, width, channels)``.
        """

    def compare_to(self, other: 'Image') -> float:
        """Compare this image to another one.

        Computes the mean squared difference of the RGBA channels over all pixels,
        normalized to the range 0 to 1. Both images must be RGBA and have the same size.

        Args:
            other: Image to compare to.

        Returns:
            ``0`` if the images are equal, larger values for larger differences.
        """
