class XmlOptions(Data):
    """XML options for parsing and serialization."""

    removeNamespaces: bool = False
    """Strip namespaces when parsing: tags and attributes are local names, declarations are dropped."""

    customNamespacePrefixes: Optional[dict[str, str]] = None
    """Serialization: prefixes to use instead of the default ones (namespace uri -> prefix)."""

    defaultNamespace: Optional['XmlNamespace'] = None
    """Serialization: elements in this namespace are written without a prefix."""

    doctype: Optional[str] = None
    """Serialization: document type definition (DTD), written after the XML declaration."""

    compactWhitespace: bool = False
    """Collapse whitespace in text content (parsing and serialization)."""

    withNamespaceDeclarations: bool = False
    """Serialization: declare all namespaces used in the tree on the root element."""

    withSchemaLocations: bool = False
    """Serialization: add ``xsi:schemaLocation`` for declared namespaces that have a schema location."""

    withXmlDeclaration: bool = False
    """Serialization: write the ``<?xml ...?>`` declaration."""


class XmlElement(Iterable):
    """XML Element.

    Implements a subset of the ``ElementTree.Element`` API.

    ``tag`` is either a local name (``Point``) or a Clark name (``{http://www.opengis.net/gml/3.2}Point``);
    ``name`` is always the local name. Prefixed names never occur in a tree: ``tag()`` resolves ``ID:name``
    to a Clark name, the parser resolves prefixes against the document's declarations. The element itself
    (constructor, ``add()``, ``set()``) takes names as they are; it has no namespace map to resolve against.
    """

    tag: str
    """Tag name, local or Clark."""

    name: str
    """Element name (tag without a namespace)."""

    text: str
    """Text before first subelement."""

    tail: str
    """Text after this element's end tag."""

    attrib: dict
    """Dictionary of element attributes."""

    namespaces: list[XmlNamespace]
    """Namespaces declared on this element (``prefix == ''`` for the default namespace)."""

    def __len__(self) -> int: ...

    def __iter__(self) -> Iterator['XmlElement']: ...

    def __getitem__(self, item: int) -> 'XmlElement': ...

    def append(self, subelement: 'XmlElement'):
        """Add a child at the end of the list of children.

        Args:
            subelement: The element to add.
        """

    def clear(self):
        """Remove the attributes, namespace declarations, children, text and tail of this element."""

    def extend(self, subelements: Iterable['XmlElement']):
        """Add children at the end of the list of children.

        Args:
            subelements: The elements to add.
        """

    def find(self, path: str) -> Optional['XmlElement']:
        """Find the first matching subelement.

        Args:
            path: Tag name or path in ``ElementTree`` syntax, with local or Clark names.

        Returns:
            The element, or ``None`` if nothing matches.
        """

    def require(self, path: str) -> 'XmlElement':
        """Find the first matching subelement, which must exist.

        Args:
            path: Tag name or path in ``ElementTree`` syntax, with local or Clark names.

        Returns:
            The element.

        Raises:
            gws.lib.xmlx.Error: If nothing matches.
        """

    def findall(self, path: str) -> list['XmlElement']:
        """Find all matching subelements.

        Args:
            path: Tag name or path in ``ElementTree`` syntax, with local or Clark names.

        Returns:
            A list of elements in document order.
        """

    def findtext(self, path: str, default: str = '') -> str:
        """Find the text of the first matching subelement.

        Args:
            path: Tag name or path in ``ElementTree`` syntax, with local or Clark names.
            default: Value to return if nothing matches.

        Returns:
            The text of the element, or ``default``.
        """

    def get(self, key: str, default: str = '') -> str:
        """Get an attribute value.

        Args:
            key: Attribute name, local or Clark.
            default: Value to return if the attribute does not exist.

        Returns:
            The attribute value, or ``default``.
        """

    def insert(self, index: int, subelement: 'XmlElement'):
        """Insert a child at the given position.

        Args:
            index: Position in the list of children.
            subelement: The element to insert.
        """

    def items(self) -> Iterable[tuple[str, Any]]:
        """Get the attributes.

        Returns:
            The attributes as ``(name, value)`` pairs.
        """

    def iter(self, tag: Optional[str] = None) -> Iterable['XmlElement']:
        """Iterate over this element and all its descendants, depth-first.

        Args:
            tag: Only return elements with this tag; ``None`` or ``*`` returns all elements.

        Returns:
            An iterator of elements, starting with this element if it matches.
        """

    def iterfind(self, path: str) -> Iterable['XmlElement']:
        """Iterate over all matching subelements.

        Args:
            path: Tag name or path in ``ElementTree`` syntax, with local or Clark names.

        Returns:
            An iterator of elements in document order.
        """

    def itertext(self) -> Iterable[str]:
        """Iterate over the text content of this element and its descendants.

        Returns:
            An iterator of the non-empty texts and tails in document order, without the tail of this element.
        """

    def keys(self) -> Iterable[str]:
        """Get the attribute names.

        Returns:
            The attribute names.
        """

    def remove(self, other: 'XmlElement'):
        """Remove a child.

        Args:
            other: The child to remove.

        Raises:
            ValueError: If the element is not a child of this element.
        """

    def set(self, key: str, value: Any):
        """Set an attribute.

        Args:
            key: Attribute name, local or Clark.
            value: Attribute value.
        """

    # extensions

    def hasattr(self, key: str) -> bool:
        """Check if an attribute exists.

        Args:
            key: Attribute name, local or Clark.

        Returns:
            ``True`` if the attribute exists.
        """

    def isa(self, *names: str) -> bool:
        """Check if the local name of this element matches one of the given names, case-insensitively.

        Args:
            *names: Local names.

        Returns:
            ``True`` if the name matches.
        """

    def add(self, tag: str, attrib: Optional[dict] = None, **extra) -> 'XmlElement':
        """Create a new element and add it as a child.

        Names are taken as they are (local or Clark); ``ID:name`` resolution is done by ``tag()`` only.

        Args:
            tag: Tag name, local or Clark.
            attrib: Attributes.
            **extra: Additional attributes.

        Returns:
            The new element.
        """

    def children(self) -> list['XmlElement']:
        """Get the children of this element.

        Returns:
            The list of children. This is the internal list, not a copy.
        """

    def declare(self, *namespaces: XmlNamespace):
        """Add namespace declarations to this element.

        The declarations are written as ``xmlns`` attributes on output. Namespaces already declared
        with the same prefix and URI are skipped.

        Args:
            *namespaces: Namespaces to declare.
        """

    def findfirst(self, *paths) -> Optional['XmlElement']:
        """Find the first element that matches one of the given paths.

        Args:
            *paths: Tag names or paths in ``ElementTree`` syntax, tried in order.

        Returns:
            The first match, or ``None``. Without paths, the first child, or ``None`` if there are no children.
        """

    def textof(self, *paths) -> str:
        """Get the text of the first matching element that has text.

        Args:
            *paths: Tag names or paths in ``ElementTree`` syntax, tried in order.

        Returns:
            The text, or an empty string if no matching element has text.
        """

    def textlist(self, *paths, deep=False) -> list[str]:
        """Collect texts from subelements.

        Texts are stripped, empty texts are skipped.

        Args:
            *paths: Tag names or paths in ``ElementTree`` syntax. Without paths, the direct children are used.
            deep: If ``True``, also collect texts from all descendants of the found elements.

        Returns:
            A list of texts in document order.
        """

    def textdict(self, *paths, deep=False) -> dict[str, str]:
        """Collect texts from subelements, keyed by tag.

        Texts are stripped, empty texts are skipped. If several elements have the same tag, the last text wins.

        Args:
            *paths: Tag names or paths in ``ElementTree`` syntax. Without paths, the direct children are used.
            deep: If ``True``, also collect texts from all descendants of the found elements.

        Returns:
            A dict of tags (local or Clark) and texts.
        """

    def to_string(self, opts: Optional[XmlOptions] = None) -> str:
        """Serialize this element and its subtree.

        Args:
            opts: Serialization options.

        Returns:
            An XML string.

        Raises:
            gws.lib.xmlx.WriteError: If the tree contains an invalid or prefixed name.
            gws.lib.xmlx.NamespaceError: If a namespace is unknown, or one prefix is used for different URIs.
        """

    def to_dict(self) -> dict:
        """Convert the element tree to a dict.

        Returns:
            A dict with the keys ``tag``, ``attrib``, ``text``, ``tail`` and ``children``,
            where ``children`` is a list of such dicts.
        """
