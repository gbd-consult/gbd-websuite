class Root:
    """Root node of the object tree."""

    app: 'Application'
    """Application object."""
    specs: 'SpecRuntime'
    """Specs runtime."""
    configErrors: list
    """List of configuration errors."""
    configWarnings: list
    """List of configuration warnings."""

    nodes: list['Node']
    """All nodes in the tree, in the order of creation."""
    uidMap: dict[str, 'Node']
    """Mapping from uids to nodes."""
    uidCount: int
    """Counter for generated uids."""
    configStack: list['Node']
    """Nodes being configured, from the outermost to the current one."""
    configPaths: list[str]
    """Paths of the configuration files."""

    def __init__(self, specs: 'SpecRuntime'):
        """Create an empty root.

        Args:
            specs: Specs runtime.
        """
        tree_impl.root_init(self, specs)

    def initialize(self, obj, config):
        """Initialize a node and record configuration errors.

        Args:
            obj: The node.
            config: Configuration.

        Returns:
            ``True`` if the node was initialized, ``False`` if it failed.
        """
        return tree_impl.root_initialize(self, obj, config)

    def post_initialize(self):
        """Run ``post_configure`` on all nodes, in the reverse order of creation.

        Errors are logged and recorded in ``configErrors``.
        """
        return tree_impl.root_post_initialize(self)

    def activate(self):
        """Run ``activate`` on all nodes."""
        return tree_impl.root_activate(self)

    def config_warning(self, message: str):
        """Register a configuration warning.

        The warning is logged immediately and reported again after the configuration is complete.
        The object stack is only available when called from ``configure`` or ``post_configure``.

        Args:
            message: Warning message.
        """
        return tree_impl.root_config_warning(self, message)

    def find_all(self, classref: Optional[ClassRef] = None) -> list['Node']:
        """Find all objects that match a specific class.

        Args:
            classref: Class reference.

        Returns:
            A list of objects.
        """
        return tree_impl.root_find_all(self, classref)

    def find_first(self, classref: Optional[ClassRef] = None) -> Optional['Node']:
        """Find the first object that matches a specific class.

        Args:
            classref: Class reference.

        Returns:
            An object or ``None``.
        """
        return tree_impl.root_find_first(self, classref)

    def get(self, uid: str = None, classref: Optional[ClassRef] = None) -> Optional['Node']:
        """Get an object by its unique ID.

        Args:
            uid: Object uid.
            classref: Class reference. If provided, ensures that the object matches the reference.

        Returns:
            An object or ``None``.
        """
        return tree_impl.root_get(self, uid, classref)

    def object_count(self) -> int:
        """Return the number of objects in the tree.

        Returns:
            The number of objects.
        """
        return tree_impl.root_object_count(self)

    def create(
        self,
        classref: ClassRef,
        parent: Optional['Node'] = None,
        config: Config = None,
        **kwargs,
    ) -> Optional['Node']:
        """Create an object.

        Args:
            classref: Class reference.
            parent: Parent object.
            config: Configuration.
            **kwargs: Additional configuration properties.

        Returns:
            A newly created object or ``None`` if the object cannot be initialized.
        """
        return tree_impl.root_create(self, classref, parent, config, **kwargs)

    def create_shared(self, classref: ClassRef, config: Config = None, **kwargs) -> Optional['Node']:
        """Create a shared object, attached directly to the root.

        If the config has no uid, it is computed from the class reference and the configuration.
        If an object with this uid already exists, it is returned instead of creating a new one.

        Args:
            classref: Class reference.
            config: Configuration.
            **kwargs: Additional configuration properties.

        Returns:
            A newly created object or ``None`` if the object cannot be initialized.
        """
        return tree_impl.root_create_shared(self, classref, config, **kwargs)

    def create_temporary(self, classref: ClassRef, config: Config = None, **kwargs) -> Optional['Node']:
        """Create a temporary object, not attached to the tree.

        Args:
            classref: Class reference.
            config: Configuration.
            **kwargs: Additional configuration properties.

        Returns:
            A newly created object or ``None`` if the object cannot be initialized.
        """
        return tree_impl.root_create_temporary(self, classref, config, **kwargs)

    def create_application(self, config: Config = None, **kwargs) -> 'Application':
        """Create the Application object.

        Args:
            config: Configuration.
            **kwargs: Additional configuration properties.

        Returns:
            The Application object.
        """
        return tree_impl.root_create_application(self, config, **kwargs)


def create_root(specs: 'SpecRuntime') -> Root:
    """Create a new root object.

    Args:
        specs: Specs runtime.

    Returns:
        The root object.
    """
    return Root(specs)


def save_root(root: Root, path: str = None) -> str:
    """Pickle the root object to a file.

    ``sys.path`` is pickled next to it, to ``<path>.syspath``, so that ``load_root`` can restore it.

    Args:
        root: The root object.
        path: File path. Defaults to ``config.pickle`` in the config directory.

    Returns:
        The file path.
    """
    return tree_impl.save_root(root, path)


def load_root(path: str = None) -> Root:
    """Load a pickled root object, activate it and make it the current root.

    ``sys.path`` is restored first, so that plugin modules can be imported.

    Args:
        path: File path. Defaults to ``config.pickle`` in the config directory.

    Returns:
        The root object.
    """
    return tree_impl.load_root(path)


def activate_root(root: Root) -> Root:
    """Activate the root object and make it the current root.

    Args:
        root: The root object.

    Returns:
        The root object.
    """
    return tree_impl.activate_root(root)


def deactivate_root():
    """Remove the current root."""
    return tree_impl.deactivate_root()


def get_root() -> Root:
    """Return the current root object.

    Returns:
        The root object set by ``activate_root`` or ``load_root``.

    Raises:
        Error: If there is no current root.
    """
    return tree_impl.get_root()


def props_of(obj: Object, user: 'User', *context) -> Optional['Props']:
    """Generate props for an object, if the user is allowed to use it.

    Nested objects the user cannot read are removed from the result.

    Args:
        obj: The object.
        user: The user.
        *context: Context objects for the permission check.

    Returns:
        A ``Props`` object, or ``None`` if the user cannot use the object.

    Raises:
        Error: If the object's ``props`` returns an invalid type.
    """
    return tree_impl.props_of(obj, user, *context)
