CrsName: TypeAlias = int | str
"""A CRS code like ``EPSG:3857`` or a SRID like ``3857``."""


class CrsFormat(Enum):
    """CRS name format."""

    none = ''
    """No format."""
    crs = 'crs'
    """Like ``crs84``."""
    srid = 'srid'
    """Like ``3857``."""
    epsg = 'epsg'
    """Like ``EPSG:3857``."""
    url = 'url'
    """Like ``http://www.opengis.net/gml/srs/epsg.xml#3857``."""
    uri = 'uri'
    """Like ``http://www.opengis.net/def/crs/epsg/0/3857``."""
    urnx = 'urnx'
    """Like ``urn:x-ogc:def:crs:EPSG:3857``."""
    urn = 'urn'
    """Like ``urn:ogc:def:crs:EPSG::3857``."""


class Axis(Enum):
    """Axis orientation."""

    xy = 'xy'
    """XY (longitude/latitude) axis orientation."""
    yx = 'yx'
    """YX (latitude/longitude) axis orientation."""


class Bounds(Data):
    """Geo-referenced extent: an extent together with its CRS."""

    crs: 'Crs'
    """Coordinate reference system of the extent."""
    extent: Extent
    """Extent in the coordinates of ``crs``."""


class Crs:
    """Coordinate reference system."""

    axis: Axis
    """Axis orientation."""
    base: int
    """Base CRS code."""
    bounds: Bounds
    """CRS own Bounds."""
    coordinatePrecision: int
    """Preferred precision for coordinates in this CRS."""
    datum: str
    """Datum."""
    epsg: str
    """Name in the "epsg" format."""
    extent: Extent
    """CRS own Extent."""
    isGeographic: bool
    """This CRS is geographic."""
    isProjected: bool
    """This CRS is projected."""
    isYX: bool
    """This CRS has a lat/lon axis."""
    name: str
    """CRS name."""
    proj4text: str
    """Proj4 definition."""
    srid: int
    """CRS SRID."""
    uom: Uom
    """CRS unit."""
    uri: str
    """Name in the "uri" format."""
    url: str
    """Name in the "url" format."""
    urn: str
    """Name in the "urn" format."""
    urnx: str
    """Name in the "urnx" format."""
    wgsExtent: Extent
    """CRS Extent in the WGS projection."""
    wgsMaxExtent: Extent
    """Maximal extent that makes sense for this CRS, in the WGS projection."""
    wkt: str
    """WKT definition."""

    def axis_for_format(self, fmt: 'CrsFormat') -> Axis:
        """Get the axis orientation implied by a CRS name format.

        For CRSs with a lat/lon axis, the orientation depends on how the CRS is named.
        We adhere to the GeoServer convention: the ``srid``, ``epsg``, ``url`` and ``uri``
        formats imply XY, the ``urn`` and ``urnx`` formats imply YX
        (see https://docs.geoserver.org/latest/en/user/services/wfs/axis_order.html).
        For XY CRSs, the own axis is always returned.

        Args:
            fmt: CRS name format.

        Returns:
            The axis orientation.
        """

    def clip_wgs_extent(self, wgs_extent: Extent) -> Optional[Extent]:
        """Clip a WGS extent to the maximal extent of this CRS.

        Args:
            wgs_extent: Extent in the WGS projection.

        Returns:
            The clipped extent in the WGS projection, or ``None`` if there is no intersection.
        """

    def extent_size_in_meters(self, extent: Extent) -> Size:
        """Calculate the width and height of an extent in meters.

        For projected CRSs, the extent size is returned as is. For geographic CRSs,
        geodesic distances on the WGS84 ellipsoid are measured along the middle
        latitude and the middle longitude of the extent.

        Args:
            extent: Extent in this CRS.

        Returns:
            A ``(width, height)`` tuple in meters.

        Raises:
            ``gws.lib.crs.Error``: If this is a projected CRS with units other than meters.
        """

    def point_offset_in_meters(self, xy: Point, dist: float, az: int) -> Point:
        """Calculate a point at a given distance and direction from another point.

        Args:
            xy: Point in this CRS.
            dist: Distance in meters.
            az: Azimuth in degrees (0 = North, 90 = East, etc.).

        Returns:
            The offset point in this CRS.

        Raises:
            ``gws.lib.crs.Error``: If this is a projected CRS with units other than meters.
        """

    def to_geojson(self) -> dict:
        """Return a GeoJSON representation of the CRS.

        The CRS is represented as a "named CRS" with its ``urn`` name,
        as per the 2008 GeoJSON specification (https://geojson.org/geojson-spec#named-crs).

        Returns:
            A GeoJSON ``crs`` dict.
        """

    def to_string(self, fmt: Optional['CrsFormat'] = None) -> str:
        """Return the name of the CRS in a given format.

        Args:
            fmt: Format to use, ``CrsFormat.epsg`` by default.

        Returns:
            The CRS name, like ``EPSG:3857``.
        """

    def transform_extent(self, extent: Extent, crs_to: 'Crs') -> Extent:
        """Transform an Extent from this CRS to another.

        The transformation goes through WGS84. If the extent is very large
        (almost the whole world) and the target CRS has a limited area of use,
        the result is computed by sampling points, so that it stays finite.

        Args:
            extent: Extent in this CRS.
            crs_to: Target CRS.

        Returns:
            The transformed Extent, with min and max values in order.
        """

    def transform_resolution(self, extent: Extent, res: float, crs_to: 'Crs') -> float:
        """Transform a resolution over an extent from this CRS to another.

        The returned resolution is the finest one found at a set of sample points of the extent,
        so that the target resolution is never coarser than the source resolution anywhere in the extent.

        Args:
            extent: Extent in this CRS.
            res: Resolution in units of this CRS per pixel.
            crs_to: Target CRS.

        Returns:
            The resolution in units of the target CRS per pixel, or ``0.0`` if the transformation fails.
        """

    def transformer(self, crs_to: 'Crs') -> Callable:
        """Create a transformer function to another CRS.

        The function always uses the XY (easting/longitude first) axis order.

        Args:
            crs_to: Target CRS.

        Returns:
            A function that takes ``x, y`` and returns a transformed ``(x, y)`` tuple.
        """
